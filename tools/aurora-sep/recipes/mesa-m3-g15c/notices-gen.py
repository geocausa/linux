#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Write the licence notices for a Mesa prefix package.

notices-gen.py SRCDIR BUILDDIR OUT PKGNAME PREFIX PROGRAMS ELF...

PROGRAMS is the comma-separated list of the package's own small programs.

Reads the compile units of the given (still unstripped) ELF files, classifies
the licence of every compiled source file, and writes OUT: a summary by licence,
the verbatim notices that must accompany binary copies, and the copyright lines
of every compiled source file.
"""
import collections
import os
import re
import subprocess
import sys

srcdir, builddir, out, pkgname, prefix, programs = sys.argv[1:7]
elfs = sys.argv[7:]
programs = [p for p in programs.split(',') if p]
src_prefix = '../' + os.path.basename(os.path.normpath(srcdir)) + '/'

# The three files of the AGX3 encoder that carry no licence header.
UNHEADERED_ENCODER = {
    'src/asahi/compiler/agx3_compose/agx3_compose.c',
    'src/asahi/compiler/agx3_compose/agx3b_tables.c',
    'src/asahi/compiler/agx3_compose/agx3c_tables.c',
}


def compile_units(path):
    text = subprocess.run(['readelf', '--debug-dump=info', '--dwarf-depth=1', path],
                          capture_output=True, text=True, errors='replace').stdout
    names, in_cu = [], False
    for line in text.splitlines():
        if 'DW_TAG_compile_unit' in line:
            in_cu = True
        elif in_cu and 'DW_AT_name' in line:
            names.append(re.sub(r'.*DW_AT_name\s*:\s*(\(indirect[^)]*\):\s*)?', '', line).strip())
            in_cu = False
    return names


def classify(text):
    head = text[:8000]
    if 'A Bison parser, made by' in head:
        return 'Bison output (GPL-3.0-or-later WITH Bison-exception-2.2)'
    m = re.search(r'SPDX-License-Identifier:\s*([A-Za-z0-9.+-]+(?: (?:OR|AND|WITH) [A-Za-z0-9.+-]+)*)', head)
    if m:
        return m.group(1)
    flat = re.sub(r'\s+', ' ', head)
    if 'Permission is hereby granted, free of charge' in flat:
        return 'MIT'
    if "Uses Jimenez's MLAA" in flat:
        return 'LicenseRef-MLAA'
    if 'Berkeley SoftFloat' in flat:
        return 'BSD-3-Clause'
    if 'Permission to use, copy, modify, distribute, and sell this software' in flat:
        return 'HPND-sell-variant'
    if 'Redistribution and use in source and binary forms' in flat:
        return 'BSD (see notice)'
    if 'flex' in flat.lower() and 'scanner' in flat.lower():
        return 'Flex output'
    return None


def leading_comment(text):
    m = re.match(r'\s*(/\*.*?\*/)', text, re.S)
    return m.group(1) if m else ''


cus = sorted({cu for e in elfs for cu in compile_units(e)})
by_licence = collections.defaultdict(list)
verbatim = {}
copyrights = set()
for cu in cus:
    if cu.startswith(src_prefix):
        rel, path, origin = cu[len(src_prefix):], os.path.join(srcdir, cu[len(src_prefix):]), 'source'
    else:
        rel, path, origin = cu, os.path.join(builddir, cu), 'generated'
    try:
        text = open(path, errors='replace').read()
    except OSError:
        by_licence['(file not found)'].append(rel)
        continue
    lic = classify(text)
    if rel in UNHEADERED_ENCODER:
        lic = 'NO HEADER (AGX3 encoder)'
    elif lic is None:
        if rel.startswith('src/util/blake3/'):
            lic = 'CC0-1.0 OR Apache-2.0 (BLAKE3 1.8.2)'
        elif origin == 'generated':
            lic = 'MIT (generated by a Mesa build script)'
        else:
            lic = 'MIT (Mesa default, docs/license.rst)'
    by_licence[lic].append(rel)
    if lic in ('LicenseRef-MLAA', 'BSD-3-Clause', 'HPND-sell-variant', 'BSD (see notice)', 'BSL-1.0'):
        verbatim.setdefault(leading_comment(text), []).append(rel)
    for line in text[:8000].splitlines():
        m = re.search(r'(Copyright\b.*)', line)
        if m and re.search(r'\d{4}', m.group(1)):
            copyrights.add(re.sub(r'\s*\*/\s*$', '', m.group(1)).strip())

with open(out, 'w') as f:
    w = f.write
    title = f'{pkgname}: licences and notices'
    w(title + '\n' + '=' * len(title) + '\n\n')
    w(f'This package is a build of Mesa 26.1.4 with Asahi Honeykrisp additions, installed in\n'
      f'{prefix}, plus {len(programs)} small programs ({", ".join(programs)}). Mesa\'s own\n'
      'licence statement is license.rst, and the full licence texts are in licenses/, both in\n'
      'this directory. In short: most of Mesa is MIT, and individual files may carry other\n'
      'licences.\n\n')
    w(f'Compiled into the libraries: {len(cus)} source files, by licence:\n\n')
    for lic in sorted(by_licence, key=lambda k: (-len(by_licence[k]), k)):
        w(f'  {len(by_licence[lic]):5d}  {lic}\n')
    w('\nFiles not under MIT, and the files with no licence header:\n')
    for lic in sorted(by_licence):
        if lic.startswith('MIT'):
            continue
        w(f'\n  {lic}:\n')
        for rel in sorted(by_licence[lic]):
            w(f'    {rel}\n')
    w('\nsrc/asahi/compiler/agx3_compose/{agx3_compose.c,agx3b_tables.c,agx3c_tables.c} carry no\n'
      'licence header; the other AGX3 encoder files in the same tree are MIT, Copyright 2026\n'
      'Aurora Silicon.\n')
    w(f'\nThe programs {", ".join(programs)} are MIT (their sources say so).\n')
    w('\nThe precompiled GPU kernels (libagx, libpoly) are compiled at build time with\n'
      'libclc from the LLVM project (Apache-2.0 WITH LLVM-exception); the LLVM exception\n'
      'covers portions of it embedded in compiled form.\n')
    w('\nBinary redistribution notices\n-----------------------------\n\n')
    w('Uses Jimenez\'s MLAA. Copyright (C) 2010 by Jorge Jimenez, Belen Masia,\n'
      'Jose I. Echevarria, Fernando Navarro and Diego Gutierrez.\n\n')
    for notice, files in sorted(verbatim.items(), key=lambda kv: kv[1][0]):
        w('Notice of ' + ', '.join(sorted(files)) + ':\n\n' + notice + '\n\n')
    w('Copyright lines of the compiled source files\n--------------------------------------------\n\n')
    for c in sorted(copyrights):
        w(c + '\n')
print(f'notices-gen: {len(cus)} compile units, {len(by_licence)} licence groups, '
      f'{len(copyrights)} copyright lines')
